class HTTPTests(Base):
    def test_real_request_encoding_and_auth_header(self):
        http = HTTP({"url": "https://printer.example/prefix", "api_key_env": "TEST_ORCA_KEY"})
        response = Mock()
        response.__enter__ = Mock(return_value=response)
        response.__exit__ = Mock(return_value=False)
        response.read.return_value = b'{"ok":true}'
        http.opener = Mock()
        http.opener.open.return_value = response
        path = self.base / "tiny.gcode"
        path.write_text(GCODE)
        with patch.dict(os.environ, {"TEST_ORCA_KEY": "test-secret-not-real"}):
            http.upload("/api/files/local", path, "unique.gcode", {"print": "false"})
        req = http.opener.open.call_args.args[0]
        self.assertEqual(req.full_url, "https://printer.example/prefix/api/files/local")
        self.assertEqual(req.get_header("X-api-key"), "test-secret-not-real")
        self.assertIn(b'name="print"\r\n\r\nfalse', req.data)
        self.assertIn(b'filename="unique.gcode"', req.data)

    def test_server_error_body_does_not_leak(self):
        http = HTTP({"url": "https://printer.example"})
        http.opener = Mock()
        http.opener.open.side_effect = urllib.error.HTTPError("https://printer.example", 401, "secret body", {}, io.BytesIO(b"secret"))
        with self.assertRaises(OrcaError) as ctx:
            http.request("GET", "/api/printer")
        self.assertNotIn("secret", str(ctx.exception))

    def test_redirect_never_forwards_credentials(self):
        from orca_plugin.printers import NoRedirect
        with self.assertRaisesRegex(OrcaError, "redirected"):
            NoRedirect().redirect_request(None, None, 302, "", {}, "https://other.example")


